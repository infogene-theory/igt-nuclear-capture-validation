class 核素拓扑:
    """封装一个靶核的全部拓扑信息与边界条件。"""

    def __init__(self, Z, N):
        self.Z = Z
        self.N = N
        self.A = Z + N
        self.形变类 = 判定形变类(Z, N)
        self.beta2 = 估算四极形变(Z, N, self.形变类)
        self.壳修正 = 估算壳修正_MEV(Z, N)

        # 边界条件（若表中有）
        bc = 边界条件表.get((Z, N))
        self.有边界条件 = bc is not None
        if bc:
            self.核素名 = bc["核素"]
            self.基态自旋 = bc["自旋"]
            self.基态宇称 = bc["宇称"]
            self.Bn = bc["Bn"]
            self.D0实验 = bc.get("D0_eV")
            self.S0实验 = bc.get("S0")
            self.S1实验 = bc.get("S1", 0.12e-4)
            self.Gg实验 = bc.get("Gg_meV")
            self.第一激发态_MEV = bc.get("第一激发态_MEV")
            self.离散态 = bc.get("离散态", [])
            self.热截面实验 = bc.get("热截面_b")
            self.共振积分实验 = bc.get("共振积分_b")
            self.束缚态 = bc.get("束缚态", [])
            self.锚共振 = bc.get("锚共振", [])
        else:
            self.核素名 = "Z%dN%d" % (Z, N)
            self.基态自旋 = None
            self.基态宇称 = None
            self.Bn = None
            self.束缚态 = []
            self.锚共振 = []
            self.第一激发态_MEV = None
            self.离散态 = []

    def 汇总(self):
        lines = [
            "核素：%s  (Z=%d, N=%d, A=%d)" % (self.核素名, self.Z, self.N, self.A),
            "形变类：%s，β2≈%.2f" % (self.形变类, self.beta2),
            "壳修正 δW≈%.2f MeV" % self.壳修正,
        ]
        if self.有边界条件:
            lines.append("基态 Jπ = %.1f%s" %
                         (self.基态自旋, "+" if self.基态宇称 > 0 else "-"))
            lines.append("中子结合能 Bn = %.3f MeV" % self.Bn)
            lines.append("[实验] D0=%.2f eV, S0=%.2e, Gg=%d meV" %
                         (self.D0实验, self.S0实验, self.Gg实验))
        return "\n".join(lines)


