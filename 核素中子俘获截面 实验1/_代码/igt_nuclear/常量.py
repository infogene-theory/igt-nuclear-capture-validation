import math

# ---------------------------------------------------------------
# 基本物理常量（CODATA / 核物理标准值）
# ---------------------------------------------------------------
光速 = 2.99792458e8                  # m/s
约化普朗克常量 = 1.054571817e-34      # J·s
普朗克常量 = 6.62607015e-34           # J·s
基本电荷 = 1.602176634e-19            # C
电子质量 = 9.1093837015e-31           # kg
中子质量 = 1.67492749804e-27          # kg
质子质量 = 1.67262192369e-27          # kg
原子质量单位 = 1.66053906660e-27      # kg
玻尔兹曼常量 = 1.380649e-23           # J/K

# 能量换算
焦耳每MeV = 1.0e6 * 基本电荷          # 1 MeV 对应的焦耳数
MEV_TO_J = 焦耳每MeV
EV_TO_J = 基本电荷
J_TO_MEV = 1.0 / 焦耳每MeV

# ℏc （常用核物理常数）
HC_BAR_MEV_FM = 约化普朗克常量 * 光速 / 焦耳每MeV * 1.0e15   # ℏc，单位 MeV·fm
HC_MEV_FM = 普朗克常量 * 光速 / 焦耳每MeV * 1.0e15           # hc，单位 MeV·fm

# 中子相关
中子静能_MEV = 中子质量 * 光速**2 / 焦耳每MeV                # 中子静能，MeV

# ---------------------------------------------------------------
# 中子波数与能量换算
# ---------------------------------------------------------------
def 中子波数(能量_eV):
    """
    由中子动能（eV）计算波数 k，单位 fm^-1。
    非相对论：k = sqrt(2 m_n E) / ℏ
    严格常数：k [fm^-1] = 2.19696e-4 * sqrt(E [eV])
    （由 k² = 2mc²E/(ℏc)² 推导）
    """
    return 2.19696e-4 * math.sqrt(max(能量_eV, 0.0))


def 中子约化波长(能量_eV):
    """
    中子约化波长 λ_bar = 1/k，单位 fm。
    """
    k = 中子波数(能量_eV)
    return 1.0 / k if k > 0 else float('inf')


# ---------------------------------------------------------------
# 全局核模型常量（全局固定，非逐核拟合）
# ---------------------------------------------------------------
class 全局核常量:
    """ Woods-Saxon 势与费米气体的全局系统学常量（对所有核素相同）。"""

    # Woods-Saxon 几何（中子）
    势深度_MEV = -49.0          # 中心势深度 V0，MeV
    半径参数_fm = 1.27          # r0，fm，R = r0 * A^(1/3)
    弥散_fm = 0.67              # 表面弥散 a，fm
    自旋轨道系数 = 0.44         # V_so / V0 比例
    自旋轨道半径_fm = 1.32      # 自旋轨道项半径参数
    自旋轨道弥散_fm = 0.66      # 自旋轨道项弥散

    # 费米气体能级密度
    能级密度系数 = 0.086        # α，MeV^-1·核子^-1，a = αA（实验校准全局值）
    壳阻尼 = 0.05              # γ，MeV^-1（Ignatyuk 壳阻尼）
    配对隙系数 = 12.0          # Δ = 12/sqrt(A)，MeV

    # GDR 流体力学标度（普适常量）
    GDR系数1 = 31.2            # c1，MeV（A^-1/3 项）
    GDR系数2 = 20.6            # c2，MeV（A^-1/6 项）
    GDR典型宽度_MEV = 5.0      # 球形核 GDR 宽度，MeV（A~200）

    # GQR
    GQR系数 = 63.0             # E_GQR = 63 A^-1/3，MeV


# ---------------------------------------------------------------
# 靶核半径
# ---------------------------------------------------------------
def 核半径_fm(A):
    """核半径 R = r0 A^(1/3)，fm。"""
    return 全局核常量.半径参数_fm * A ** (1.0 / 3.0)


