# -*- coding: utf-8 -*-
"""
IGT 核 τ 谱生成器 — 门态骨架与聚类检测模块
================================================
强判据（隐藏拓扑序）的核心模块。

两部分：
1. 门态骨架生成：在中子能量轴上生成确定性门态位置；
2. 门态聚类检测：对观测共振，定量检验其是否在门态位置处聚类
   （对比"均匀/无门态"统计零模型）。

检测工具：
- 共振到最近门态的距离分布 + K-S 检验；
- 共振密度的傅里叶功率谱（门态周期 → 谱峰）；
- 折叠相位分布（Rayleigh 检验）。
"""

import math
import numpy as np
from scipy import stats, signal


# ===============================================================
# 一、门态骨架生成
# ===============================================================
def 生成门态骨架(能量上限_eV, 门态平均间距_eV, rng=None, 声子微扰=0.15):
    """
    在 [0, 能量上限] 生成门态位置。
    基础为等间隔序列（集体模驱动），叠加小幅声子频率微扰（确定性伪随机）。

    返回门态能量数组。
    """
    n = int(能量上限_eV / 门态平均间距_eV) + 1
    基础 = np.arange(1, n + 1) * 门态平均间距_eV
    if rng is not None and 声子微扰 > 0:
        微扰 = rng.normal(0, 门态平均间距_eV * 声子微扰, n)
        基础 = 基础 + 微扰
    return 基础[基础 <= 能量上限_eV * 1.1]


# ===============================================================
# 二、门态聚类检测
# ===============================================================
def 到最近门态距离(共振位置, 门态位置):
    """每个共振到最近门态的（有符号）距离，单位同门态。"""
    共振 = np.asarray(共振位置)
    门 = np.asarray(门态位置)
    距离 = np.full(len(共振), np.nan)
    for i, x in enumerate(共振):
        j = np.argmin(np.abs(门 - x))
        距离[i] = x - 门[j]
    return 距离


def 聚类K_S检验(共振位置, 门态位置):
    """
    用 K-S 检验比较"共振到门态距离分布"与"均匀零模型"。
    零模型：若共振均匀分布，到最近等间隔门态的距离在 [-D/2,D/2] 均匀。
    返回 (KS统计量, p值, 门态平均间距)。
    p值很小 → 拒绝均匀零模型 → 存在聚类。
    """
    门 = np.sort(np.asarray(门态位置))
    D门 = np.mean(np.diff(门))
    距离 = 到最近门态距离(共振位置, 门)
    # 均匀零模型 CDF：在 [-D/2,D/2] 均匀
    零模型 = np.random.default_rng(0).uniform(-D门 / 2, D门 / 2, len(距离))
    ks, p = stats.ks_2samp(距离, 零模型)
    return ks, p, D门


def 密度功率谱(共振位置, 能量上限_eV, n_bin=2000,
             最小周期_eV=30.0, 最大周期_eV=500.0):
    """
    计算共振计数密度的傅里叶功率谱。
    门态周期结构 → 功率谱在对应频率出现峰。
    仅在 [最小周期, 最大周期] 物理窗口内寻峰（排除整体趋势与高频计数噪声）。
    返回 (频率[1/eV], 功率, 主峰周期_eV, 峰显著性 z)
    """
    bins = np.linspace(0, 能量上限_eV, n_bin + 1)
    计数, _ = np.histogram(共振位置, bins)
    # 去均值
    x = 计数 - 计数.mean()
    # 功率谱
    频 = np.fft.rfftfreq(n_bin, d=(能量上限_eV / n_bin))
    功率 = np.abs(np.fft.rfft(x)) ** 2
    # 物理周期窗口 → 频率窗口
    f_hi = 1.0 / 最小周期_eV
    f_lo = 1.0 / 最大周期_eV
    窗口 = (频 >= f_lo) & (频 <= f_hi)
    频窗 = 频[窗口]
    功窗 = 功率[窗口]
    if len(功窗) == 0:
        return 频, 功率, np.nan, 0.0
    idx = np.argmax(功窗)
    峰频 = 频窗[idx]
    峰周期 = 1.0 / 峰频 if 峰频 > 0 else np.nan
    # 显著性 z：峰相对窗口背景的均值与标准差
    均值 = 功窗.mean()
    std = max(功窗.std(), 1e-12)
    z = (功窗[idx] - 均值) / std
    return 频, 功率, 峰周期, z


def 折叠相位Rayleigh(共振位置, 候选周期):
    """
    把共振位置按候选周期折叠为相位 [0,1)，用 Rayleigh 检验判断相位是否集中。
    返回 (Rayleigh Z, p值, 合向量长度R)。
    R→1 且 p小 → 强周期聚类。
    """
    相位 = (np.asarray(共振位置) % 候选周期) / 候选周期 * 2 * math.pi
    n = len(相位)
    C = np.sum(np.cos(相位)) / n
    S = np.sum(np.sin(相位)) / n
    R = math.hypot(C, S)
    Z = n * R ** 2
    # Rayleigh 近似 p 值
    p = math.exp(-Z)
    return Z, p, R


